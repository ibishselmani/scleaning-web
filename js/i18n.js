export function makeT(lang) {
  const i = IDX[lang] ?? 0;
  return (key, ...args) => {
    const entry = TEXTS[key];
    const s = entry ? entry[i] || entry[0] : key;
    return args.length ? s.replace(/\{(\d)\}/g, (_, n) => String(args[n] ?? '')) : s;
  };
}

export function savedLang() {
  try {
    const l = localStorage.getItem('scleaning.web.lang');
    if (l && l in IDX) return l;
  } catch { /* ignore */ }
  const nav = (navigator.language || 'de').slice(0, 2);
  return nav in IDX ? nav : 'de';
}
export function saveLang(l) {
  try { localStorage.setItem('scleaning.web.lang', l); } catch { /* ignore */ }
}
